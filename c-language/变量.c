#include <stdio.h>

int main()
{
    int a = 10;
    float b = 3.14;
    char c = 'A';
    char str[] = "Hello, World!";
    printf("整数 a 的值为: %d\n", a);
    printf("浮点数 b 的值为: %f\n", b);
    printf("字符 c 的值为: %c\n", c);
    printf("字符串 str 的值为: %s\n", str);
    a + b;
    printf("a + b 的值为: %f\n", a + b);
    int vxp = 100;
    vxp = vxp + 2;
    printf("vxp 的值为: %d\n", vxp);
    return 0;
}