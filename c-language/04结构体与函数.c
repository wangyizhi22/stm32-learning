/* ==================================================================
 * 04 结构体与函数
 *
 * 本课主题：把结构体传进函数，并让函数真正改到调用者的那份数据
 *
 * 全课最重要的一句话：
 *   结构体默认是【传值】——函数拿到的是复印件，改不到外面；
 *   想改到外面，必须传【地址】，也就是传【指针】。
 * ================================================================== */

#define _CRT_SECURE_NO_WARNINGS   /* 让 VS 放行 scanf 等"不安全"函数；Mac 的 clang 不管这行，留着无副作用 */

#include <stdio.h>
#include <stdlib.h>   /* 本文件没用到，保留 */
#include <time.h>     /* 本文件没用到，保留 */
#include <string.h>   /* strcpy 需要它 */

/* ------------------------------------------------------------------
 * 定义结构体类型，同时起一个别名 s
 *
 * 拆开看这句：
 *     typedef struct student { ... } s;
 *     └─起别名─┘ └─结构体标签─┘   └─别名─┘
 *
 *   结构体标签 student 只是"内部名"，起了别名之后基本用不上；
 *   真正好用的是别名 s，从此 "s stu;" 就等于 "struct student stu;"
 *
 * 别名不改变任何内存布局，纯粹是少打几个字。
 * ------------------------------------------------------------------ */
typedef struct student
{
    char name[100];   /* 名字：字符【数组】，不是指针，容量固定 100 字节 */
    int  age;         /* 年龄 */
} s;

/* ------------------------------------------------------------------
 * 函数声明（又叫函数原型）
 *
 * 只有分号、没有函数体。作用是"提前告诉编译器：有这么个函数"，
 * 这样 main 里调用它时，编译器才认识这个名字、才知道参数类型。
 *
 * 注意参数已经从上一版的 "s st" 改成了 "s *p"：
 *     s      —— 一整个结构体（传值，会复制一份）
 *     s *    —— 指向结构体的【指针】，本质只是一个地址
 *               （Mac 64 位下占 8 字节；STM32 那种 32 位机上占 4 字节）
 *
 * 传指针的代价 = 复制一个地址，无论结构体多大都是这么多。
 * 传值的代价 = 复制整个结构体，越大越亏。
 * ------------------------------------------------------------------ */
void redefine_struct(s *p);


int main()
{
    s stu;                        /* 在栈上开辟一块 s 类型的空间，变量名 stu */
    strcpy(stu.name, "aaa");      /* 数组名不能直接 = "aaa"，必须用 strcpy 逐字符拷进去 */
    stu.age = 18;
    printf("初始%s %d\n", stu.name, stu.age);

    /* ★ 本课最关键的一行：&stu 取的是 stu 的【地址】，不是 stu 本身。
     *   函数收到的就是这份地址，顺着地址就能找回到 main 里的 stu，
     *   所以这次才能真正改到"原件"。
     *   对比上一版的 redefine_struct(stu)：那传的是整份拷贝，改完白改。 */
    redefine_struct(&stu);

    /* 验证：这次会真的变成你输入的名字和年龄 */
    printf("函数调用后 main 里的%s %d\n", stu.name, stu.age);

    return 0;
}

/* ------------------------------------------------------------------
 * 函数定义：重新录入学生信息
 *
 * 形参 s *p 表示：p 是一个指针，里面存着"某个 s 结构体的地址"
 * ------------------------------------------------------------------ */
void redefine_struct(s *p)
{
    printf("请输入学生的名字:");

    /* (*p) 的意思是：顺着 p 里存的地址，找到那个结构体本身 —— 这叫"解引用"。
     * 这里的 (*p) 就等价于 main 里的 stu。

     * (*p).name 还可以简写成 p->name，两者完全等价：
     *     (*p).name —— 先取出整个结构体 *p，再用 . 取成员   —— 写法直观
     *     p->name   —— 直接从指针指向的那个成员取            —— 写得短，实际开发更常用
     * 二者选一个就行，本文件保留直观写法。

     * 另外注意：name 前面【不用】加 &。
     * 因为 name 本身就是数组，数组名在 scanf 里会自动当成地址使用。 */
    scanf("%s", (*p).name);

    printf("请输入学生的年龄:");

    /* age 是 int，scanf 需要"int 的地址"，所以要加 &。
     * &((*p).age) 一步步读就是：
     *      p    → 指针
     *     *p    → 结构体
     *    (*p).age → 里面的 age 成员
     *  &((*p).age) → 这个成员的地址
     * 简化写法是 &p->age。 */
    scanf("%d", &((*p).age));

    printf("函数内部的%s %d\n", (*p).name, (*p).age);
}
